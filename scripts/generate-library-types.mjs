#!/usr/bin/env node
// The library service's TypeScript types, generated from its OpenAPI document.
//
//   node scripts/generate-library-types.mjs          # ask the Python app for the
//                                                    # document, write it and the types
//   node scripts/generate-library-types.mjs --check  # fail if the committed types are
//                                                    # behind the committed document (pnpm lint)
//
// The Python tests (tests/test_hub_openapi.py) fail when the committed document
// is behind the routes, so the chain routes → document → types is checked end to end.
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import openapiTS, { astToString } from "openapi-typescript";
import { libraryProject, withLibraryPython } from "./python-env.mjs";

const DOCUMENT = new URL("../packages/shared/src/generated/library-openapi.json", import.meta.url);
const TYPES = new URL("../packages/shared/src/generated/library-api.ts", import.meta.url);
const HEADER = `// Generated by \`pnpm gen:library-types\` from library-openapi.json, the library
// service's OpenAPI document. Do not edit: change the response models in
// packages/scholaraio/scholaraio/interfaces/api/responses.py and regenerate.

`;

async function render(document) {
  return HEADER + astToString(await openapiTS(document));
}

if (process.argv.includes("--check")) {
  const expected = await render(JSON.parse(readFileSync(DOCUMENT, "utf-8")));
  if (readFileSync(TYPES, "utf-8") !== expected) {
    console.error(
      "packages/shared/src/generated/library-api.ts is behind library-openapi.json: run pnpm gen:library-types",
    );
    process.exit(1);
  }
} else {
  const document = withLibraryPython(["hub"], (python) => {
    const result = spawnSync(python, ["-m", "scholaraio.interfaces.api.openapi"], {
      cwd: libraryProject,
      encoding: "utf-8",
      stdio: ["ignore", "pipe", "inherit"],
    });
    if (result.status !== 0) throw result.error ?? new Error("Could not describe the library API");
    return result.stdout;
  });
  writeFileSync(DOCUMENT, document);
  writeFileSync(TYPES, await render(JSON.parse(document)));
  console.log("Wrote library-openapi.json and library-api.ts in packages/shared/src/generated/");
}
